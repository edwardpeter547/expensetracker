"""
Safe, idempotent execution of an approved, hash-verified plan.

This module consumes a validated manifest and a separately supplied approved
plan hash, refreshes GitHub state, regenerates the plan, and only then performs
the smallest set of mutations required: creating explicitly authorized missing
issues and attaching native sub-issue relationships. Existing issues are never
modified, and duplicate or conflicting links are never silently repaired.

Creation requires two independent authorizations: the plan must have been
generated with ``--allow-create`` (bound into its hash) and the apply command
must supply ``--allow-create`` again. GitHub state is revalidated immediately
before each creation, and ambiguous mutation failures are reconciled with
read-only lookups instead of being blindly retried.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

from scripts.github_tickets import planner as planner_module
from scripts.github_tickets.github import (
    GitHubAmbiguousParentError,
    GitHubClient,
    GitHubError,
    GitHubRateLimitError,
    GitHubRequestError,
    GitHubResponseError,
    Issue,
    discover_issues,
    extract_ticket_markers,
    ticket_id_marker,
)
from scripts.github_tickets.model import Manifest
from scripts.github_tickets.planner import (
    ACTION_BLOCKED,
    ACTION_CREATE,
    ACTION_EXISTS,
    ACTION_REVIEW_REQUIRED,
    Plan,
    compute_plan_hash,
)

# Ticket creation order: parents before children.
_TYPE_ORDER = {"epic": 0, "story": 1, "task": 2}

STATUS_COMPLETED = "COMPLETED"
STATUS_PARTIAL = "PARTIAL"
STATUS_FAILED = "FAILED"

OP_SKIP = "SKIP"
OP_CREATE = "CREATE"
OP_LINK = "LINK"
OP_CONFLICT = "CONFLICT"
OP_ERROR = "ERROR"


class ExecutionError(Exception):
    """Raised when a plan cannot be safely executed (stale, unapproved, unsafe)."""


@dataclass
class Operation:
    """
    A single execution operation outcome.

    Attributes:
        op: One of ``SKIP``, ``CREATE``, ``LINK``, ``CONFLICT``, or ``ERROR``.
        target: Human-readable target (ticket id or ``parent -> child``).
        message: Description of the outcome.
        issue_number: Related issue number when applicable.
    """

    op: str
    target: str
    message: str
    issue_number: Optional[int] = None


@dataclass
class ExecutionReport:
    """
    Result of an execution attempt.

    Attributes:
        status: ``COMPLETED``, ``PARTIAL``, or ``FAILED``.
        operations: Ordered operation outcomes.
        created_issues: Ticket ids whose issues were created.
        linked: ``parent -> child`` strings for links established.
        errors: Error messages encountered.
    """

    status: str = STATUS_COMPLETED
    operations: List[Operation] = field(default_factory=list)
    created_issues: List[str] = field(default_factory=list)
    linked: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)


def verify_approved_plan(
    client: GitHubClient,
    manifest: Manifest,
    approved_hash: str,
    allow_create: bool = False,
) -> Plan:
    """Refresh GitHub state and verify the regenerated plan hash.

    The stored or supplied hash is never trusted as sufficient authorization;
    the plan is regenerated from the current manifest and GitHub state and its
    digest is compared against ``approved_hash``.

    Args:
        client: A read-only-capable :class:`GitHubClient` for the target repo.
        manifest: The validated :class:`Manifest`.
        approved_hash: The exact approved SHA-256 plan hash.
        allow_create: Whether issue creation was separately authorized at
            apply time. Must match the permission bound into the approved
            plan hash.

    Returns:
        The freshly generated :class:`Plan`.

    Raises:
        ExecutionError: If the regenerated hash differs, or the plan contains
            ``BLOCKED`` or ``REVIEW_REQUIRED`` actions, or creation was not
            authorized at execution time.
    """
    try:
        issues = client.list_issues()
        discovery = discover_issues(client, manifest.tickets, issues=issues)
    except GitHubError as exc:
        raise ExecutionError(f"GitHub state refresh failed: {exc}") from exc

    plan = planner_module.build_plan(
        manifest,
        discovery,
        str(client.repo),
        issues=issues,
        allow_create=allow_create,
    )
    current_hash = compute_plan_hash(plan)
    if current_hash != approved_hash:
        if not allow_create:
            # A hash generated by ``plan --allow-create`` will never match a
            # regeneration without creation permission. Detect that case so
            # the operator gets an actionable error instead of a bare hash
            # mismatch.
            plan_with_create = planner_module.build_plan(
                manifest,
                discovery,
                str(client.repo),
                issues=issues,
                allow_create=True,
            )
            if (
                compute_plan_hash(plan_with_create) == approved_hash
                and any(
                    action.action == ACTION_CREATE
                    for action in plan_with_create.actions
                )
            ):
                raise ExecutionError(
                    "the approved plan contains CREATE actions; rerun apply "
                    "with --allow-create"
                )
        raise ExecutionError(
            f"plan hash {current_hash} does not match approved hash {approved_hash}"
        )

    unsafe = [
        action
        for action in plan.actions
        if action.action in (ACTION_BLOCKED, ACTION_REVIEW_REQUIRED)
    ]
    if unsafe:
        raise ExecutionError(
            "plan contains unresolved actions: "
            + ", ".join(action.ticket_id for action in unsafe)
        )

    if (
        any(action.action == ACTION_CREATE for action in plan.actions)
        and not plan.allow_create
    ):
        raise ExecutionError(
            "plan contains CREATE actions but creation was not authorized"
        )

    return plan


def execute_plan(
    client: GitHubClient,
    manifest: Manifest,
    approved_hash: str,
    allow_create: bool = False,
) -> ExecutionReport:
    """
    Execute an approved plan safely and idempotently.

    Args:
        client: A :class:`GitHubClient` for the target repository.
        manifest: The validated :class:`Manifest`.
        approved_hash: The exact approved SHA-256 plan hash.
        allow_create: Whether issue creation was separately authorized at
            apply time. Must match the permission bound into the approved
            plan hash.

    Returns:
        An :class:`ExecutionReport` describing every operation and the final
        status.

    Raises:
        ExecutionError: For stale plans, unresolved actions, or state-refresh
            failures.
    """
    plan = verify_approved_plan(
        client, manifest, approved_hash, allow_create=allow_create
    )
    report = ExecutionReport()

    verified_by_ticket = {
        item["ticket_id"]: item for item in plan.verified_issues
    }
    by_id = {ticket.id: ticket for ticket in manifest.tickets if isinstance(ticket.id, str)}
    ticket_issues: Dict[str, Issue] = {}
    create_actions = [a for a in plan.actions if a.action == ACTION_CREATE]
    exists_actions = [a for a in plan.actions if a.action == ACTION_EXISTS]
    create_actions.sort(key=lambda a: (_TYPE_ORDER.get(by_id[a.ticket_id].type, 99), a.ticket_id))

    for action in exists_actions:
        try:
            issue = client.get_issue(action.issue_number)
        except GitHubError as exc:
            raise ExecutionError(f"{action.ticket_id}: {exc}") from exc

        verified = verified_by_ticket.get(action.ticket_id, {})
        if (
            verified.get("issue_number") != issue.number
            or verified.get("title") != issue.title
            or verified.get("state") != issue.state
            or verified.get("url") != issue.html_url
        ):
            raise ExecutionError(
                f"{action.ticket_id}: existing issue identity changed from the "
                f"approved plan (approved #{verified.get('issue_number')}, "
                f"fetched #{issue.number})"
            )

        ticket_issues[action.ticket_id] = issue
        report.operations.append(
            Operation(
                OP_SKIP,
                action.ticket_id,
                f"existing issue #{issue.number} preserved",
                issue.number,
            )
        )

    for action in create_actions:
        ticket = by_id[action.ticket_id]

        # Revalidate absence immediately before the mutation. The approved
        # plan was built from a slightly earlier snapshot; GitHub may have
        # changed in the meantime (including a concurrent or previous run).
        try:
            current_issues = client.list_issues()
        except GitHubError as exc:
            report.errors.append(
                f"{ticket.id}: pre-create state revalidation failed: {exc}"
            )
            report.operations.append(Operation(OP_ERROR, ticket.id, str(exc)))
            report.status = STATUS_PARTIAL
            return report

        hits = _marker_hits(current_issues, ticket.id)
        if hits:
            if len(hits) > 1:
                message = "marker matches multiple issues; refusing to create a duplicate"
                report.errors.append(f"{ticket.id}: {message}")
                report.operations.append(
                    Operation(OP_CONFLICT, ticket.id, message)
                )
                report.status = STATUS_FAILED
                return report
            existing = hits[0]
            reuse_error = _verify_reusable_issue(client, ticket, existing)
            if reuse_error is not None:
                message = (
                    f"cannot safely reuse issue #{existing.number}: {reuse_error}"
                )
                report.errors.append(f"{ticket.id}: {message}")
                report.operations.append(
                    Operation(OP_CONFLICT, ticket.id, message, existing.number)
                )
                report.status = STATUS_FAILED
                return report
            ticket_issues[ticket.id] = existing
            report.operations.append(
                Operation(
                    OP_SKIP,
                    ticket.id,
                    f"issue #{existing.number} appeared after approval; preserved",
                    existing.number,
                )
            )
            continue

        title_candidates = planner_module.plausible_title_candidates(
            ticket.title, current_issues
        )
        if title_candidates:
            numbers = ", ".join(f"#{number}" for number in title_candidates)
            message = (
                "plausible existing issue candidate(s) by title: "
                f"{numbers}; refusing to create a duplicate"
            )
            report.errors.append(f"{ticket.id}: {message}")
            report.operations.append(Operation(OP_CONFLICT, ticket.id, message))
            report.status = STATUS_FAILED
            return report

        body = _body_with_marker(manifest, ticket)
        try:
            issue = client.create_issue(
                ticket.title,
                body,
                labels=list(ticket.labels or []),
            )
        except GitHubError as exc:
            if _is_ambiguous_creation_error(exc):
                try:
                    outcome, issue, detail = _reconcile_created_issue(
                        client, ticket
                    )
                except GitHubError as reconcile_exc:
                    report.errors.append(
                        f"{ticket.id}: {exc}; reconciliation failed: {reconcile_exc}"
                    )
                    report.operations.append(
                        Operation(OP_ERROR, ticket.id, str(exc))
                    )
                    report.status = STATUS_PARTIAL
                    return report
                if outcome == "created":
                    ticket_issues[ticket.id] = issue
                    report.created_issues.append(ticket.id)
                    report.operations.append(
                        Operation(
                            OP_CREATE,
                            ticket.id,
                            f"created issue #{issue.number} (reconciled after "
                            "ambiguous response)",
                            issue.number,
                        )
                    )
                    continue
                report.errors.append(
                    f"{ticket.id}: {exc}; reconciliation: {detail}"
                )
                report.operations.append(Operation(OP_ERROR, ticket.id, str(exc)))
                report.status = STATUS_PARTIAL
                return report

            report.errors.append(f"{ticket.id}: {exc}")
            report.operations.append(Operation(OP_ERROR, ticket.id, str(exc)))
            report.status = STATUS_PARTIAL
            return report

        identity_error = _verify_created_identity(client, ticket, issue)
        if identity_error is not None:
            report.errors.append(
                f"{ticket.id}: created issue #{issue.number} could not be "
                f"verified: {identity_error}"
            )
            report.operations.append(
                Operation(OP_ERROR, ticket.id, identity_error, issue.number)
            )
            report.status = STATUS_PARTIAL
            return report

        ticket_issues[ticket.id] = issue
        report.created_issues.append(ticket.id)
        report.operations.append(
            Operation(
                OP_CREATE,
                ticket.id,
                f"created issue #{issue.number}",
                issue.number,
            )
        )

    for rel in plan.relationships:
        parent = ticket_issues.get(rel.parent_id)
        child = ticket_issues.get(rel.child_id)
        label = f"{rel.parent_id} -> {rel.child_id}"
        if parent is None or child is None:
            report.errors.append(f"{label}: missing verified issue")
            report.operations.append(Operation(OP_ERROR, label, "missing verified issue"))
            report.status = STATUS_PARTIAL
            return report

        try:
            existing_children = client.list_sub_issues(parent.number)
        except GitHubError as exc:
            report.errors.append(f"{label}: {exc}")
            report.operations.append(Operation(OP_ERROR, label, str(exc)))
            report.status = STATUS_PARTIAL
            return report

        if any(child_issue.number == child.number for child_issue in existing_children):
            report.operations.append(
                Operation(OP_SKIP, label, "child already linked to parent", child.number)
            )
            continue

        try:
            current_parent = client.get_parent_issue(child.number)
        except GitHubAmbiguousParentError as exc:
            report.errors.append(f"{label}: {exc}")
            report.operations.append(
                Operation(OP_ERROR, label, "parentless state cannot be confirmed", child.number)
            )
            report.status = STATUS_PARTIAL
            return report
        except GitHubError as exc:
            report.errors.append(f"{label}: {exc}")
            report.operations.append(Operation(OP_ERROR, label, str(exc)))
            report.status = STATUS_PARTIAL
            return report

        if current_parent is not None:
            if current_parent.number == parent.number:
                report.operations.append(
                    Operation(OP_SKIP, label, "child already linked to parent", child.number)
                )
                continue
            report.errors.append(
                f"{label}: child #{child.number} is already linked to parent "
                f"#{current_parent.number}; refusing to reparent"
            )
            report.operations.append(
                Operation(
                    OP_CONFLICT,
                    label,
                    f"child already linked to parent #{current_parent.number}",
                    child.number,
                )
            )
            report.status = STATUS_FAILED
            return report

        # Parentless is now safely confirmed: GraphQL returned parent:null
        # (see GitHubClient.get_parent_issue).
        if child.id is None:
            report.errors.append(f"{label}: child issue #{child.number} has no id")
            report.operations.append(
                Operation(OP_ERROR, label, "child issue has no id", child.number)
            )
            report.status = STATUS_FAILED
            return report

        try:
            client.add_sub_issue(parent.number, child.id)
        except GitHubError as exc:
            report.errors.append(f"{label}: {exc}")
            report.operations.append(Operation(OP_ERROR, label, str(exc)))
            report.status = STATUS_PARTIAL
            return report

        report.linked.append(label)
        report.operations.append(
            Operation(OP_LINK, label, f"linked child #{child.number} to parent #{parent.number}", child.number)
        )

    if report.errors and report.status == STATUS_COMPLETED:
        report.status = STATUS_PARTIAL
    return report


def _same_title(expected: str, actual: str) -> bool:
    """Compare two titles after collapsing whitespace.

    Args:
        expected: The title from the manifest.
        actual: The title reported by GitHub.

    Returns:
        ``True`` when the titles are equal after whitespace collapsing.
    """
    return " ".join((expected or "").split()) == " ".join((actual or "").split())


def _marker_hits(issues: List[Issue], ticket_id: str) -> List[Issue]:
    """Return non-pull-request issues carrying ``ticket_id``'s marker.

    Args:
        issues: Current issues to search.
        ticket_id: The manifest ticket identifier whose marker is searched.

    Returns:
        The matching issues in listing order.
    """
    marker = ticket_id_marker(ticket_id)
    return [
        issue
        for issue in issues
        if not issue.is_pull_request and issue.body and marker in issue.body
    ]


def _issue_in_repo(client: GitHubClient, issue: Issue) -> bool:
    """Return whether an issue's URL belongs to the client's repository.

    Args:
        client: The client whose repository is authoritative.
        issue: The issue to check.

    Returns:
        ``True`` when the issue URL matches the canonical URL for the target
        repository and issue number.
    """
    expected = f"https://github.com/{client.repo}/issues/{issue.number}"
    return issue.html_url.rstrip("/") == expected


def _verify_created_identity(
    client: GitHubClient, ticket, issue: Issue
) -> Optional[str]:
    """Verify a freshly created issue's identity, or return an error message.

    Args:
        client: The client used for creation.
        ticket: The manifest ticket that was created.
        issue: The issue returned by GitHub.

    Returns:
        ``None`` when the identity is consistent, otherwise a human-readable
        error message.
    """
    if not _same_title(ticket.title, issue.title):
        return "created issue title differs from the manifest title"
    if issue.body is None or ticket_id_marker(ticket.id) not in issue.body:
        return "created issue body is missing its stable marker"
    if not _issue_in_repo(client, issue):
        return "created issue URL does not match the target repository"
    return None


def _verify_reusable_issue(
    client: GitHubClient, ticket, issue: Issue
) -> Optional[str]:
    """Verify an existing issue can be safely reused, or return an error.

    Reuse is allowed only when the issue belongs to the target repository,
    carries exactly this ticket's stable marker, and has a matching title.
    Any mismatch is reported; existing issues are never modified or repaired.

    Args:
        client: The client whose repository is authoritative.
        ticket: The manifest ticket being reconciled.
        issue: The candidate existing issue.

    Returns:
        ``None`` when the issue is safe to reuse, otherwise an actionable
        error message.
    """
    if not _issue_in_repo(client, issue):
        return (
            f"issue #{issue.number} URL {issue.html_url!r} does not match "
            f"the target repository"
        )
    markers = extract_ticket_markers(issue.body)
    if markers != [ticket.id]:
        return (
            f"issue #{issue.number} marker specification does not match "
            f"ticket {ticket.id!r}"
        )
    if not _same_title(ticket.title, issue.title):
        return (
            f"issue #{issue.number} title {issue.title!r} differs from the "
            f"manifest title"
        )
    return None


def _is_ambiguous_creation_error(exc: GitHubError) -> bool:
    """Return whether a create failure could still have been processed.

    Timeouts, network errors, 5xx responses, rate limits, and malformed
    responses are ambiguous because the mutation may have reached GitHub.
    Definitive 4xx responses (other than rate limits) are not ambiguous.

    Args:
        exc: The create failure to classify.

    Returns:
        ``True`` when the outcome should be reconciled with a read-only lookup.
    """
    if isinstance(exc, (GitHubRateLimitError, GitHubResponseError)):
        return True
    if isinstance(exc, GitHubRequestError):
        return exc.status_code is None or exc.status_code >= 500
    return False


def _reconcile_created_issue(
    client: GitHubClient, ticket
) -> Tuple[str, Optional[Issue], str]:
    """Reconcile a create whose HTTP outcome was ambiguous.

    Args:
        client: The client whose repository is authoritative.
        ticket: The manifest ticket that may have been created.

    Returns:
        A tuple ``(outcome, issue, detail)`` where ``outcome`` is one of
        ``"created"``, ``"unknown"``, ``"ambiguous"``, or ``"mismatch"``.

    Raises:
        GitHubError: If the read-only reconciliation lookup fails.
    """
    issues = client.list_issues()
    hits = _marker_hits(issues, ticket.id)
    if not hits:
        return "unknown", None, "no issue with marker found; creation outcome unknown"
    if len(hits) > 1:
        return "ambiguous", None, "multiple issues with marker found"
    issue = hits[0]
    if not _same_title(ticket.title, issue.title):
        return (
            "mismatch",
            issue,
            f"issue #{issue.number} with marker has a different title",
        )
    if not _issue_in_repo(client, issue):
        return (
            "mismatch",
            issue,
            f"issue #{issue.number} does not belong to the target repository",
        )
    return "created", issue, ""


def _body_with_marker(manifest: Manifest, ticket) -> str:
    """
    Return the ticket body with its stable marker prepended.

    Args:
        manifest: The validated manifest.
        ticket: The manifest ticket whose body is read.

    Returns:
        The marker line followed by the body file contents.

    Raises:
        ExecutionError: If the body file cannot be read.
    """
    marker = ticket_id_marker(ticket.id)
    try:
        body_text = (manifest.root / ticket.body).read_text(encoding="utf-8")
    except OSError as exc:
        raise ExecutionError(f"Ticket {ticket.id!r} body is unreadable: {exc}") from exc
    if marker not in body_text:
        return f"{marker}\n\n{body_text}"
    return body_text
